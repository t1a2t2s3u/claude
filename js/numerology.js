const MASTER_NUMBERS = new Set([11, 22, 33]);

function digitSum(n) {
  return String(n)
    .split('')
    .reduce((sum, ch) => sum + Number(ch), 0);
}

/**
 * 生年月日から運命数を計算する。
 * 年月日の全桁を合計し、1桁(またはマスターナンバー)になるまで還元する。
 * @param {number} year 例: 1990
 * @param {number} month 1〜12
 * @param {number} day 1〜31
 * @returns {number} 1〜9, 11, 22, 33 のいずれか
 */
export function getLifePathNumber(year, month, day) {
  let n = digitSum(year) + digitSum(month) + digitSum(day);
  while (n > 9 && !MASTER_NUMBERS.has(n)) {
    n = digitSum(n);
  }
  return n;
}
