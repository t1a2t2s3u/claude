function buildDeck() {
  const deck = MAJOR_ARCANA.map((card, i) => ({
    id: i,
    arcana: 'major',
    ...card,
  }));

  let id = MAJOR_ARCANA.length;
  for (const suit of SUITS) {
    for (const rank of RANKS) {
      const key = `${suit.key}-${rank.key}`;
      const [upKeywords, upMessage, revKeywords, revMessage] = MINOR_TEXTS[key];
      const rankAdvice = RANK_ADVICE[rank.key];
      deck.push({
        id: id++,
        arcana: 'minor',
        suit: suit.name,
        name: `${suit.name}の${rank.label}`,
        roman: '',
        image: `assets/tarot/${key}.jpg`,
        upright: { keywords: upKeywords, message: upMessage },
        reversed: { keywords: revKeywords, message: revMessage },
        advice: {
          love: { up: rankAdvice.love, rev: rankAdvice.love },
          work: { up: rankAdvice.work, rev: rankAdvice.work },
          money: { up: rankAdvice.money, rev: rankAdvice.money },
        },
      });
    }
  }
  return deck;
}

export const TAROT_CARDS = buildDeck();

/**
 * カードと正逆から、恋愛・仕事・金運のアドバイスを取り出す。
 */
export function getTarotAdvice(card, isReversed) {
  const side = isReversed ? 'rev' : 'up';
  return {
    love: card.advice.love[side],
    work: card.advice.work[side],
    money: card.advice.money[side],
  };
}

/**
 * 「今日の一枚」を引く。フルデッキ78枚から、日付+シードで決定的に決まる。
 * @param {string} personalSeed 引く人を表すシード(例: 'virgo:i:O')
 * @param {Date} [date] 省略時は今日
 * @returns {{ card: object, isReversed: boolean, dateKey: string }}
 */
export function getDailyTarot(personalSeed, date = new Date()) {
  const dateKey = formatDateKey(date);
  const rng = mulberry32(hashString(`${dateKey}:tarot:${personalSeed}`));
  const card = TAROT_CARDS[Math.floor(rng() * TAROT_CARDS.length)];
  const isReversed = rng() < 0.35; // 逆位置は約35%。毎日引く占いなので正位置多めに。
  return { card, isReversed, dateKey };
}

/**
 * 過去・現在・未来の3枚引き。重複しない3枚を決定的に選ぶ。
 * @param {string} personalSeed 引く人を表すシード
 * @param {Date} [date] 省略時は今日
 * @returns {Array<{ position: string, card: object, isReversed: boolean }>}
 */
export function getThreeCardSpread(personalSeed, date = new Date()) {
  const dateKey = formatDateKey(date);
  const rng = mulberry32(hashString(`${dateKey}:spread3:${personalSeed}`));
  const positions = ['過去', '現在', '未来'];
  const chosen = new Set();
  return positions.map((position) => {
    let index;
    do {
      index = Math.floor(rng() * TAROT_CARDS.length);
    } while (chosen.has(index));
    chosen.add(index);
    return { position, card: TAROT_CARDS[index], isReversed: rng() < 0.35 };
  });
}
