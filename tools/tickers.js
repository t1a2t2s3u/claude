export const PRESETS = {
  jp: JP,
  us: US,
  all: [...JP, ...US],
};

/** "7203,AAPL,6758" のような指定を銘柄定義に変換する（未知のコードも通す） */
export function resolveSymbols(list) {
  const known = new Map(PRESETS.all.map((s) => [s.symbol.toUpperCase(), s]));
  return list.map((raw) => {
    const code = raw.trim();
    const hit = known.get(code.toUpperCase());
    if (hit) return hit;

    const isJp = /^\d{4}$/.test(code);
    return {
      symbol: code.toUpperCase(),
      name: code,
      sector: '—',
      market: isJp ? 'JP' : 'US',
      currency: isJp ? 'JPY' : 'USD',
      lot: isJp ? 100 : 1,
      yahoo: isJp ? `${code}.T` : code.toUpperCase(),
      stooq: isJp ? `${code}.jp` : `${code.toLowerCase()}.us`,
    };
  });
}
